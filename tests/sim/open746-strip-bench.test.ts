const KIT = "open746-strip-bench.elf"
const kit = example(KIT)
const ANALYSER_HZ = 1e6
const RECORD_SECONDS = 0.32
const GPIO_BASE = 0x40020000
const GPIO_STRIDE = 0x400
const PORTS = 9
const ALL_OUTPUT = 0x55555555
const PA9_MODE = 3 << 18
const SDRAM = { clock: "P20-20", chipSelect: "P19-31", clockEnable: "P19-32" }

const leadName = (lead: number) => `D${lead}`
const mcuOf = new Map(open746ic.pins.map((p) => [p.id, p.mcu]))

const BENCH_PARTS: Record<string, PartState> = {
  MUSB: { on: false },
  SW1: { on: false },
  S2: { on: false },
  USB: { on: true },
  JMP6: { on: false },
  JMP2_1: { on: false },
  JMP2_2: { on: false },
  JMP2_3: { on: false },
  JMP2_4: { on: false },
  OTG_VBUS: { on: false },
  OTG_PWR: { on: false },
  OTG_FLG: { on: false },
}

function kitOnTheBench() {
  const doc = lab1Board.build(GRID)
  const u = doc.objects.find((o) => o.def === "open746i-c")!
  u.props = { ...u.props, firmware: KIT, firmwareData: kit.toString("base64") }
  const loop = new SimLoop()
  loop.setDoc(doc)
  loop.setParts({ ...doc.parts, ...Object.fromEntries(Object.entries(BENCH_PARTS).map(([part, state]) => [partKey(u.id, part), state])) })
  loop.setLogic(true)
  loop.setRunning(true)
  let clock = 0
  let last: Snapshot | null = null
  loop.advance(clock)
  const run = (seconds: number, each: (snap: Snapshot) => void = () => {}) => {
    const end = clock + seconds * 1000
    while (clock < end) {
      clock = Math.min(end, clock + 20)
      loop.advance(clock)
      last = loop.snapshot()
      if (last) each(last)
    }
    return last!
  }
  const record = (leads: (string | null)[], seconds = RECORD_SECONDS): Capture => {
    const probes = leads.flatMap((pin, lead) => (pin ? [{ id: leadName(lead), a: pinKey(u.id, pin), b: null }] : []))
    loop.setProbes(probes)
    const store = new LogicStore()
    const start = run(0.02).time
    store.clear()
    run(seconds, (snap) => {
      if (snap.logic) store.push(snap.logic, snap.traceProbes)
    })
    expect(store.dropped, "the analyser kept every edge").toBe(false)
    const channels = probes.map(({ id }): Channel => {
      const edges = store.edges(id)
      expect(edges, `${id} recorded`).not.toBeNull()
      const toggles = edges!.times.subarray(0, edges!.count).filter((t) => t >= start)
      const before = edges!.count - toggles.length
      const initial = toggles.length ? edges!.levels[before] === 0 : edges!.last
      return { name: id, initial, toggles }
    })
    return { start, end: store.end, channels }
  }
  return { loop, u, run, record }
}

let captures: Capture[] | null = null
function benchCaptures() {
  if (captures) return captures
  const bench = kitOnTheBench()
  bench.run(0.05)
  captures = BENCH_GROUPS.map((group) => bench.record(group.leads))
  return captures
}

const leadsOf = (group: (typeof BENCH_GROUPS)[number]) =>
  new Map(group.leads.flatMap((pin, lead) => (pin ? [[leadName(lead), pin] as const] : [])))

function samplesOf(capture: Capture) {
  const count = Math.floor((capture.end - capture.start) * ANALYSER_HZ)
  const samples = new Uint8Array(count)
  const bits = capture.channels.map((c) => Number(c.name.slice(1)))
  for (let i = 0; i < count; i++) {
    const t = capture.start + i / ANALYSER_HZ
    capture.channels.forEach((channel, c) => {
      if (levelAt(channel, t)) samples[i]! |= 1 << bits[c]!
    })
  }
  return { samples, bits }
}

async function sigrokSession(capture: Capture) {
  const { samples } = samplesOf(capture)
  const metadata = [
    "[global]",
    "sigrok version=0.6.0-git-883c2ac",
    "",
    "[device 1]",
    "capturefile=logic-1",
    "total probes=8",
    "samplerate=1 MHz",
    "total analog=0",
    ...capture.channels.map((c) => `probe${Number(c.name.slice(1)) + 1}=${c.name}`),
    "unitsize=1",
    "",
  ].join("\n")
  return writeZip([
    { path: "version", content: "2" },
    { path: "metadata", content: metadata },
    { path: "logic-1-1", content: samples },
  ])
}

function pulseViewCsv(capture: Capture) {
  const { samples, bits } = samplesOf(capture)
  const lines = [
    "; CSV generated by libsigrok 0.6.0-git-883c2ac",
    "; from Saleae Logic on Mon Oct 12 12:00:00 2026",
    `; Channels (${capture.channels.length}/8): ${capture.channels.map((c) => c.name).join(", ")}`,
    "; Samplerate: 1 MHz",
    capture.channels.map(() => "logic").join(","),
  ]
  for (const sample of samples) lines.push(bits.map((bit) => (sample >> bit) & 1).join(","))
  return lines.join("\n") + "\n"
}

const summary = (readings: Reading[]) => readings.map((r) => `${r.channel} ${r.pin} ${r.found}`)

describe("the pin-strip kit for the bench", () => {
  it("walks the pads in the order the 18 lead positions cover the strips, top to bottom, left strip first", () => {
    const leads = BENCH_GROUPS.flatMap((g) => g.leads)
    expect(BENCH_GROUPS).toHaveLength(18)
    for (const group of BENCH_GROUPS) expect(group.leads, `rows ${group.firstRow}–${group.lastRow} of the ${group.strip} strip`).toHaveLength(8)
    expect(leads.filter((pin) => pin !== null).map((pin) => mcuOf.get(pin!)), "the pads under the leads, in order").toEqual(SLOT_PADS)
    expect(new Set(SLOT_PADS).size, "distinct pads").toBe(140)
    const parked = BENCH_GROUPS.flatMap((g) => g.leads.flatMap((pin, lead) => (pin ? [] : [`${g.strip} rows ${g.firstRow}–${g.lastRow} ${leadName(lead)}`])))
    expect(parked, "leads parked over the strips' power pins").toEqual(["left rows 17–20 D2", "left rows 33–36 D7", "right rows 17–20 D4", "right rows 17–20 D5"])
    for (const pin of STRIP_LABELS.keys()) expect.soft(isGpio(STRIP_LABELS.get(pin)!) === leads.includes(pin), `${pin} (${STRIP_LABELS.get(pin)}) has a lead iff it is an I/O`).toBe(true)
  })

  it("runs on HSI with every strip pad an output but PA9, touching nothing the emulator does not model", async () => {
    const bench = kitOnTheBench()
    const snap = bench.run(0.05)
    const status = snap.mcus[bench.u.id]!
    expect(status.firmware).toBe(KIT)
    expect(status.running, "core running").toBe(true)
    expect(status.halted).toBeNull()
    expect(status.sysclk, "SYSCLK").toBe(16e6)
    expect(status.faults).toEqual([])
    expect(status.unmodelled).toEqual([])
    const reply = await bench.loop.inspect(bench.u.id, { ranges: Array.from({ length: PORTS }, (_, port) => ({ addr: GPIO_BASE + port * GPIO_STRIDE, size: 4 })) })
    const modes = reply!.memory.map((m) => new DataView(m.bytes.buffer, m.bytes.byteOffset).getUint32(0, true))
    expect(modes[0]! & PA9_MODE, "PA9 stays an input").toBe(0)
    expect(modes.map((m, port) => (port === 0 ? m | (ALL_OUTPUT & PA9_MODE) : m)), "every other pad is an output").toEqual(Array(PORTS).fill(ALL_OUTPUT))
  })

  it("decodes every strip I/O to the pad its silkscreen names, eight leads at a time, PA9 never driven", () => {
    const wrong: string[] = []
    benchCaptures().forEach((capture, g) => {
      const group = BENCH_GROUPS[g]!
      const report = decodeStripBench(capture, leadsOf(group))
      const where = `${group.strip} rows ${group.firstRow}–${group.lastRow}`
      expect(report.problem, where).toBeNull()
      expect.soft(report.slotSeconds / SLOT_SECONDS, `${where}: slot length`).toBeNear(1, 1e-4)
      expect.soft(report.cycles, `${where}: complete cycles`).toBeGreaterThanOrEqual(1)
      for (const r of report.readings) if (!r.ok) wrong.push(`${where} ${r.channel} ${r.pin} (${r.label}): ${r.found} — ${r.detail}`)
      const neverDriven = report.readings.find((r) => r.label === NEVER_DRIVEN)
      if (neverDriven) expect(neverDriven.verdict, `${NEVER_DRIVEN} on ${neverDriven.pin}`).not.toBe("pad")
    })
    expect(wrong).toEqual([])
    const decoded = BENCH_GROUPS.flatMap((group, g) => decodeStripBench(benchCaptures()[g]!, leadsOf(group)).readings)
    expect(decoded.filter((r) => r.ok && r.verdict === "pad"), "pads identified").toHaveLength(139)
  })

  it("reads the same from the .sr session PulseView saves and from its CSV export", async () => {
    for (const g of [3, 4, 13]) {
      const group = BENCH_GROUPS[g]!
      const capture = benchCaptures()[g]!
      const direct = summary(decodeStripBench(capture, leadsOf(group)).readings)
      const fromSession = decodeStripBench(await readSigrokSession(await sigrokSession(capture)), leadsOf(group))
      expect(fromSession.problem).toBeNull()
      expect(summary(fromSession.readings), `group ${g + 1} from .sr`).toEqual(direct)
      const fromCsv = decodeStripBench(readCsv(pulseViewCsv(capture)), leadsOf(group))
      expect(fromCsv.problem).toBeNull()
      expect(summary(fromCsv.readings), `group ${g + 1} from CSV`).toEqual(direct)
    }
  })

  it("keeps the SDRAM deselected (CS high) at every rising edge of its clock", () => {
    const bench = kitOnTheBench()
    bench.run(0.05)
    const capture = bench.record([SDRAM.clock, SDRAM.chipSelect, SDRAM.clockEnable], 2 * CYCLE_SLOTS * SLOT_SECONDS)
    const [clock, chipSelect] = capture.channels as [Channel, Channel, Channel]
    const rises = Array.from(clock.toggles).filter((t) => !levelAt(clock, t - 1e-9) && levelAt(clock, t))
    expect(rises.length, "two clock rises a cycle: into the sync and into PG8's own slot").toBeGreaterThanOrEqual(3)
    for (const t of rises) expect.soft(levelAt(chipSelect, t), `CS at the clock edge at ${(t * 1e3).toFixed(3)} ms`).toBe(true)
  })
})
